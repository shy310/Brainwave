/** Russian counted nouns: 1 (минута), 2–4 (минуты), 5+ (минут), with 11–14 like 5+. */
const pl = (n: number, one: string, few: string, many: string) => {
  const d = n % 10, h = n % 100;
  return d === 1 && h !== 11 ? one : d >= 2 && d <= 4 && (h < 12 || h > 14) ? few : many;
};
const count = (n: number, one: string, few: string, many: string) => `${n} ${pl(n, one, few, many)}`;

